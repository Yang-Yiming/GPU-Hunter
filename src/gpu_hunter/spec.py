"""Load and validate workflow YAML: WorkflowSpec / JobSpec."""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from .parsing import coerce_cmd, coerce_path, ensure_interpreter, parse_int_list, parse_size_mb


class SpecError(ValueError):
    pass


_SCHEDULES = ("greedy", "sequential")

_JOB_KEYS = {"name", "cmd", "gpu-num", "mem-per-gpu", "prefer", "allow", "env", "log", "cwd"}
_DEFAULT_KEYS = _JOB_KEYS - {"name", "cmd"}


@dataclass
class JobSpec:
    name: str
    cmd: list[str]
    gpu_num: int = 1
    mem_per_gpu_mb: int | None = None
    prefer: tuple[int, ...] = ()
    allow: frozenset[int] | None = None
    env: dict[str, str] = field(default_factory=dict)
    log: Path | None = None            # None + passthrough_log=False -> generated by the scheduler
    passthrough_log: bool = False      # True when log: "-", output goes to the terminal
    cwd: Path | None = None


@dataclass
class WorkflowSpec:
    path: Path
    schedule: str = "greedy"
    interval_s: float = 5.0
    stable_rounds: int = 3
    idle_mem_mb: int = 500
    idle_util: int = 5
    grace_s: float = 45.0
    claim_stable_s: float = 8.0        # how long a foreign pid must persist to call it preemption
    heartbeat_s: float = 120.0
    max_attempts: int = 3              # per job; preempted jobs are retried at most this often
    retry_delay_s: float = 2.0         # base delay between preemption retries (doubles each time)
    jobs: list[JobSpec] = field(default_factory=list)


def _err(ctx: str, msg: str) -> SpecError:
    return SpecError(f"{ctx}: {msg}")


def _expect_mapping(value, ctx: str) -> dict:
    if not isinstance(value, dict):
        raise _err(ctx, "must be a mapping (table)")
    return value


def _opt_int(value, ctx: str, default: int | None = None, *, minimum: int | None = None) -> int | None:
    if value is None:
        return default
    if isinstance(value, bool) or not isinstance(value, int):
        raise _err(ctx, f"must be an integer, got {value!r}")
    if minimum is not None and value < minimum:
        raise _err(ctx, f"must be >= {minimum}, got {value}")
    return value


def _opt_float(value, ctx: str, default: float, *, minimum: float) -> float:
    if value is None:
        return default
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise _err(ctx, f"must be a number, got {value!r}")
    v = float(value)
    if v < minimum:
        raise _err(ctx, f"must be >= {minimum}, got {v}")
    return v


def _opt_size(value, ctx: str, *, minimum: int = 1) -> int | None:
    if value is None:
        return None
    if isinstance(value, str):
        try:
            size = parse_size_mb(value)
        except ValueError as e:
            raise _err(ctx, str(e)) from None
    else:
        size = _opt_int(value, ctx, minimum=minimum)
    if size is not None and size < minimum:
        raise _err(ctx, f"must be >= {minimum}")
    return size


def _opt_ids(value, ctx: str, *, as_set: bool):
    if value is None:
        return None
    try:
        ids = parse_int_list(value)
    except ValueError as e:
        raise _err(ctx, str(e)) from None
    return frozenset(ids) if as_set else tuple(ids)


def _opt_env(value, ctx: str) -> dict[str, str]:
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise _err(ctx, "env must be a mapping from strings to strings")
    out = {}
    for k, v in value.items():
        if v is None or isinstance(v, (dict, list)):
            raise _err(f"{ctx}.env[{k}]", "value must be a scalar")
        out[str(k)] = str(v)
    return out


def _build_job(raw, index: int, defaults: dict) -> JobSpec:
    raw = _expect_mapping(raw, f"jobs[{index}]")
    unknown = set(raw) - _JOB_KEYS
    if unknown:
        raise _err(f"jobs[{index}]", f"unknown fields {sorted(unknown)}, allowed: {sorted(_JOB_KEYS)}")
    ctx = f"jobs[{index}]"

    name = raw.get("name")
    if name is not None and (not isinstance(name, str) or not name.strip()):
        raise _err(f"{ctx}.name", "must be a non-empty string")

    cmd_value = raw.get("cmd")
    if cmd_value is None:
        raise _err(ctx, "missing required field cmd")
    try:
        cmd = ensure_interpreter(coerce_cmd(cmd_value, ctx))
    except ValueError as e:
        raise _err(ctx, str(e)) from None

    gpu_num = _opt_int(
        raw.get("gpu-num", defaults.get("gpu-num")), f"{ctx}.gpu-num", 1, minimum=1
    )
    mem = _opt_size(raw.get("mem-per-gpu", defaults.get("mem-per-gpu")), f"{ctx}.mem-per-gpu")
    prefer = _opt_ids(raw.get("prefer", defaults.get("prefer")), f"{ctx}.prefer", as_set=False) or ()
    allow = _opt_ids(raw.get("allow", defaults.get("allow")), f"{ctx}.allow", as_set=True)

    if allow is not None and len(allow) < gpu_num:
        raise _err(
            f"{ctx}.allow",
            f"only {len(allow)} GPU(s) allowed but gpu-num is {gpu_num}",
        )

    env = _opt_env(defaults.get("env"), "defaults.env")
    env.update(_opt_env(raw.get("env"), f"{ctx}.env"))

    log_v = raw.get("log", defaults.get("log"))
    log_path = None
    passthrough = False
    if log_v is not None:
        if isinstance(log_v, str) and log_v.strip() == "-":
            passthrough = True
        else:
            log_path = coerce_path(log_v, f"{ctx}.log")

    cwd_v = raw.get("cwd", defaults.get("cwd"))
    cwd = coerce_path(cwd_v, f"{ctx}.cwd") if cwd_v is not None else None

    return JobSpec(
        name=name or f"job-{index + 1}",
        cmd=cmd,
        gpu_num=gpu_num,
        mem_per_gpu_mb=mem,
        prefer=tuple(prefer),
        allow=allow,
        env=env,
        log=log_path,
        passthrough_log=passthrough,
        cwd=cwd,
    )


def load_workflow(path: str | Path) -> WorkflowSpec:
    path = Path(path)
    if not path.is_file():
        raise SpecError(f"workflow file does not exist: {path}")
    try:
        import yaml
    except ImportError:
        raise SpecError(
            "PyYAML is required for workflow mode: pip install PyYAML"
        ) from None
    try:
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as e:
        raise SpecError(f"YAML syntax error ({path}): {e}") from None
    root = _expect_mapping(doc, str(path))

    unknown = set(root) - {
        "schedule", "interval", "stable-rounds", "idle-mem", "idle-util", "grace",
        "claim-stable", "heartbeat", "max-attempts", "retry-delay", "defaults", "jobs",
    }
    if unknown:
        raise _err(str(path), f"unknown top-level fields {sorted(unknown)}")

    schedule = root.get("schedule", "greedy")
    if schedule not in _SCHEDULES:
        raise _err("schedule", f"must be one of {', '.join(map(repr, _SCHEDULES))}, got {schedule!r}")

    jobs_raw = root.get("jobs")
    if not jobs_raw or not isinstance(jobs_raw, list):
        raise _err("jobs", "must be a non-empty list")

    defaults_raw = root.get("defaults") or {}
    defaults_raw = _expect_mapping(defaults_raw, "defaults")
    unknown_d = set(defaults_raw) - _DEFAULT_KEYS
    if unknown_d:
        raise _err("defaults", f"unknown fields {sorted(unknown_d)}, allowed: {sorted(_DEFAULT_KEYS)}")

    idle_mem = _opt_size(root.get("idle-mem"), "idle-mem")
    wf = WorkflowSpec(
        path=path,
        schedule=schedule,
        interval_s=_opt_float(root.get("interval"), "interval", 5.0, minimum=0.1),
        stable_rounds=_opt_int(root.get("stable-rounds"), "stable-rounds", 3, minimum=1),
        idle_mem_mb=idle_mem if idle_mem is not None else 500,
        idle_util=_opt_int(root.get("idle-util"), "idle-util", 5, minimum=0),
        grace_s=_opt_float(root.get("grace"), "grace", 45.0, minimum=0.0),
        claim_stable_s=_opt_float(root.get("claim-stable"), "claim-stable", 8.0, minimum=0.0),
        heartbeat_s=_opt_float(root.get("heartbeat"), "heartbeat", 120.0, minimum=1.0),
        max_attempts=_opt_int(root.get("max-attempts"), "max-attempts", 3, minimum=1),
        retry_delay_s=_opt_float(root.get("retry-delay"), "retry-delay", 2.0, minimum=0.0),
    )
    wf.jobs = [_build_job(j, i, defaults_raw) for i, j in enumerate(jobs_raw)]

    names = [j.name for j in wf.jobs]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        raise _err("jobs", f"duplicate name(s): {dupes}")
    return wf
